export const CATALOGS: Record<Lang, Catalog> = { en, hi, mr };
export const LANGUAGE_NAMES: Record<Lang, string> = { en: "English", hi: "हिन्दी", mr: "मराठी" };

/** Looks up `key` in `lang`, falling back to English, and fills `{placeholders}`. Unknown placeholders stay visible. */
export function t(lang: Lang, key: string, params: Record<string, string | number> = {}): string {
  const template = CATALOGS[lang][key] ?? CATALOGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

export function riskKey(code: RiskCode): string {
  return `risk.${code}`;
}
